def source_tables(configs: Iterable[str | os.PathLike]) -> dict[str, tuple[dict[str, Any], Path]]:
    """The Iceberg tables that dataset configs name, as ``{"<namespace>.<table>": (block, folder)}``.

    It reads the JSON of the configs and opens no catalog, so it is cheap and has no side effects. The block is the
    ``{"name", "format": "ICEBERG", "catalog"}`` block of the table, and the folder is the one that a relative path of
    the block resolves against, which is where the config is. A config that cannot be read as a dataset config is
    skipped, and the first config that names a table wins.

    Args:
        configs: Dataset config files, or folders of ``*.json`` configs, as the project's ``sources.configs``.
    """
    from local_data_platform import Config
    from local_data_platform.catalog.provider import catalog_namespace
    from local_data_platform.mcp_server.discovery import config_files

    found: dict[str, tuple[dict[str, Any], Path]] = {}
    for path in configs:
        for file in config_files(path):
            try:
                config = Config.from_json(file)
            except ConfigError:
                continue
            for section in ("target", "source"):
                block = config.metadata.get(section) or {}
                if str(block.get("format", "")).strip().upper() != "ICEBERG":
                    continue
                name, spec = block.get("name"), block.get("catalog")
                if not name or not isinstance(spec, dict):
                    continue
                found.setdefault(f"{catalog_namespace(spec)}.{name}",
                                 ({"name": str(name), "format": "ICEBERG", "catalog": dict(spec)}, file.parent))
    return found


def _without_own_outputs(tables: list[Any], database: Path, skipped: list[dict[str, str]]) -> list[Any]:
    """Drop the tables that a config publishes from ``database``: they are outputs of the dbt project."""
    kept = []
    for table in tables:
        if _is_published_from(table.source, database):
            skipped.append({"table": table.identifier,
                            "reason": "a config publishes it from this build file, so it is an output of the project"})
        else:
            kept.append(table)
    return kept


def _is_published_from(config_file: str, database: Path) -> bool:
    path = Path(config_file)
    if path.suffix != ".json" or not path.is_file():
        return False
    try:
        source = json.loads(path.read_text())["metadata"]["source"]
        if str(source.get("format", "")).strip().upper() != "DUCKDB":
            return False
        return resolve_path(str(source["path"]), path.parent) == database
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        return False


def _use_views(connection: Any, mode: str) -> bool:
    """Whether to register views. Never downloads the iceberg extension."""
    if mode == "copy":
        return False
    from local_data_platform.engine.duckdb import DuckDBEngine

    if DuckDBEngine(connection=connection).iceberg_extension:
        return True
    if mode == "view":
        raise EngineNotFound(f"mode='view' needs DuckDB's iceberg extension, which is not installed. {ICEBERG_HINT}")
    logger.warning("Registering the sources as copies, because DuckDB's iceberg extension is not installed. "
                   "Views are quicker and smaller. %s", ICEBERG_HINT)
    return False


def _register_one(connection: Any, table: Any, use_views: bool, mode: str,
                  previous: dict[tuple[str, str], str]) -> RegisteredSource:
    duckdb = _import_duckdb()
    iceberg = table.load()
    schema, name = ".".join(table.namespace), table.name
    snapshot = iceberg.current_snapshot()
    pinned = snapshot.snapshot_id if snapshot is not None else None
    relation = f"{_quote(schema)}.{_quote(name)}"
    connection.execute(f"CREATE SCHEMA IF NOT EXISTS {_quote(schema)}")
    # Remove what an earlier call made under this name, so a view can become a copy and back. A relation
    # that dbt made is not in the state, so it is never dropped, and creating over it fails below.
    earlier = previous.get((schema, name))
    if earlier is not None:
        connection.execute(f"DROP {'VIEW' if earlier == 'view' else 'TABLE'} IF EXISTS {relation}")

    kind, rows = "table", None
    try:
        if use_views and pinned is not None:
            try:
                connection.execute(
                    f"CREATE VIEW {relation} AS SELECT * FROM iceberg_scan({_quote_string(iceberg.metadata_location)}, "
                    f"snapshot_from_id => {int(pinned)})")
                kind = "view"
            except duckdb.CatalogException:
                raise
            except duckdb.Error as error:
                if mode == "view":
                    raise
                logger.warning("Registering %s.%s as a copy: DuckDB's iceberg_scan can't read it (%s)", schema, name,
                               str(error).splitlines()[0])
        if kind == "table":
            data = iceberg.scan(snapshot_id=pinned).to_arrow() if pinned is not None else iceberg.scan().to_arrow()
            connection.register("_ldp_copy", data)
            try:
                connection.execute(f"CREATE TABLE {relation} AS SELECT * FROM _ldp_copy")
            finally:
                try:
                    connection.unregister("_ldp_copy")
                except duckdb.TransactionException:
                    pass  # DuckDB 2.0 refuses it once the CREATE failed and aborted the transaction, which rolls back
            rows = data.num_rows
    except duckdb.CatalogException as error:
        text = str(error)
        if "already exists" not in text and "Existing object" not in text:
            raise
        raise ConfigError(f"cannot register {schema}.{name} as a dbt source: the build file already has a table "
                          f"or view with that name that dbt made. Rename the model or the table. "
                          f"{text.splitlines()[0]}") from error
    columns = tuple((str(row[0]), str(row[1])) for row in connection.execute(f"DESCRIBE {relation}").fetchall())
    logger.debug("Registered %s.%s as a %s (snapshot %s)", schema, name, kind, pinned)
    return RegisteredSource(schema, name, kind, pinned, columns, rows)


# --------------------------------------------------------------------------- state and leftovers


def _ensure_state(connection: Any) -> None:
    connection.execute(f"CREATE SCHEMA IF NOT EXISTS {_quote(STATE_SCHEMA)}")
    connection.execute(f"CREATE TABLE IF NOT EXISTS {_quote(STATE_SCHEMA)}.{_quote(STATE_TABLE)} "
                       "(schema_name VARCHAR, table_name VARCHAR, kind VARCHAR, snapshot_id BIGINT, "
                       "registered_at TIMESTAMP)")


def _read_state(connection: Any) -> dict[tuple[str, str], str]:
    rows = connection.execute(f"SELECT schema_name, table_name, kind FROM {_quote(STATE_SCHEMA)}.{_quote(STATE_TABLE)}")
    return {(schema, name): kind for schema, name, kind in rows.fetchall()}


def _write_state(connection: Any, sources: list[RegisteredSource]) -> None:
    state = f"{_quote(STATE_SCHEMA)}.{_quote(STATE_TABLE)}"
    connection.execute(f"DELETE FROM {state}")
    now = datetime.now(timezone.utc).replace(tzinfo=None)
    if sources:
        connection.executemany(f"INSERT INTO {state} VALUES (?, ?, ?, ?, ?)",
                               [(s.schema, s.name, s.kind, s.snapshot_id, now) for s in sources])


def _drop_leftovers(connection: Any, previous: dict[tuple[str, str], str],
                    sources: list[RegisteredSource]) -> list[str]:
    """Drop the relations of an earlier call whose table is gone, and the schemas that are left empty."""
    current = {(source.schema, source.name) for source in sources}
    dropped, touched = [], set()
    for (schema, name), kind in previous.items():
        if (schema, name) in current:
            continue
        connection.execute(f"DROP {'VIEW' if kind == 'view' else 'TABLE'} IF EXISTS {_quote(schema)}.{_quote(name)}")
        dropped.append(f"{schema}.{name}")
        touched.add(schema)
    for schema in sorted(touched - {"main", STATE_SCHEMA}):
        remaining = connection.execute("SELECT count(*) FROM information_schema.tables WHERE table_schema = ?",
                                       [schema]).fetchall()[0][0]
        if remaining == 0:
            connection.execute(f"DROP SCHEMA IF EXISTS {_quote(schema)}")
    return dropped


# --------------------------------------------------------------------------- the dbt sources file


def _yaml_string(value: str) -> str:
    # A JSON string is a valid YAML double-quoted scalar, so names with spaces or quotes stay safe.
    return json.dumps(value, ensure_ascii=False)


def sources_yaml(sources: Iterable[RegisteredSource]) -> str:
    """The dbt sources file for ``sources``: one dbt source per schema, one table per relation.

    It is written with plain string formatting, so LDP's core needs no YAML library.
    """
    by_schema: dict[str, list[RegisteredSource]] = {}
    for source in sources:
        by_schema.setdefault(source.schema, []).append(source)
    lines = [GENERATED_HEADER.rstrip("\n"), "version: 2"]
    if not by_schema:
        lines.append("sources: []")
    else:
        lines.append("sources:")
    for schema, tables in by_schema.items():
        lines += [f"  - name: {_yaml_string(schema)}", f"    schema: {_yaml_string(schema)}", "    tables:"]
        for table in tables:
            lines += [f"      - name: {_yaml_string(table.name)}", "        columns:"]
            for column, data_type in table.columns:
                lines += [f"          - name: {_yaml_string(column)}",
                          f"            data_type: {_yaml_string(data_type)}"]
    return "\n".join(lines) + "\n"


def _write_if_changed(path: Path, text: str) -> Path:
    path = path.resolve()
    if path.is_file() and path.read_text() == text:
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(text)
    os.replace(temporary, path)
    return path


