"""Register LDP's Iceberg tables as dbt sources in a DuckDB build file.

dbt cannot connect to an LDP catalog, so before a dbt run every Iceberg table becomes a relation
in the DuckDB file that dbt builds in, and a generated YAML file declares them as dbt sources.
The contract is ``docs/design/warehousing.md``.

* **View mode**: each relation is a persistent view over DuckDB's ``iceberg_scan`` of the table's
  metadata file, pinned to the snapshot that was current when registration started.
* **Copy mode**: each relation is a DuckDB table holding that snapshot. It works without the
  ``iceberg`` extension.
* **Auto** (the default): views when the extension loads without a download, copies otherwise.

Nothing is ever downloaded. ``duckdb`` is imported when :func:`register_sources` runs, never when
this module is imported.
"""

from __future__ import annotations

import json
import os
from collections.abc import Iterable
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from local_data_platform.exceptions import ConfigError, EngineNotFound
from local_data_platform.logger import get_logger
from local_data_platform.paths import resolve_path

logger = get_logger(__name__)

MODES = ("auto", "view", "copy")
STATE_SCHEMA = "_ldp"
STATE_TABLE = "sources"
GENERATED_HEADER = "# Generated by `ldp dbt`. It is rewritten on every build, so do not edit it.\n"
INSTALL_HINT = 'pip install "local-data-platform[duckdb]"'
ICEBERG_HINT = 'Install DuckDB\'s iceberg extension once with duckdb.connect().execute("INSTALL iceberg")'


@dataclass(frozen=True)
class RegisteredSource:
    """One relation that :func:`register_sources` created in the build file.

    Attributes:
        schema: The schema, which is the table's namespace.
        name: The relation, which is the table's name.
        kind: ``"view"`` or ``"table"`` (a copy).
        snapshot_id: The snapshot the relation is pinned to, or ``None`` for a table with no snapshot.
        columns: ``(name, DuckDB type)`` for each column.
        rows: The row count of a copy, ``None`` for a view.
    """

    schema: str
    name: str
    kind: str
    snapshot_id: int | None
    columns: tuple[tuple[str, str], ...]
    rows: int | None = None

    @property
    def identifier(self) -> str:
        """``"<schema>.<name>"``."""
        return f"{self.schema}.{self.name}"


@dataclass
class SourceRegistration:
    """What :func:`register_sources` did.

    Attributes:
        database: The DuckDB build file.
        sources: The relations created, in discovery order.
        skipped: Tables left out on purpose, each ``{"table", "reason"}``.
        unavailable: Tables that were found but cannot be read yet, each ``{"table", "reason", "source"}``.
        dropped: Relations removed because their table no longer exists.
        sources_file: The YAML file written, or ``None``.
    """

    database: Path
    sources: list[RegisteredSource] = field(default_factory=list)
    skipped: list[dict[str, str]] = field(default_factory=list)
    unavailable: list[dict[str, str]] = field(default_factory=list)
    dropped: list[str] = field(default_factory=list)
    sources_file: Path | None = None

    @property
    def mode(self) -> str:
        """``"view"`` or ``"copy"`` when every relation is one kind, else ``"mixed"``."""
        kinds = {source.kind for source in self.sources}
        if not kinds:
            return "view"
        return "mixed" if len(kinds) > 1 else ("view" if kinds == {"view"} else "copy")


def _import_duckdb() -> Any:
    try:
        import duckdb
    except ImportError as error:
        raise EngineNotFound(
            f"Registering dbt sources needs the duckdb package. Install it with: {INSTALL_HINT}") from error
    return duckdb


def _quote(name: str) -> str:
    from local_data_platform.engine.duckdb.row_filter import quote_identifier

    return quote_identifier(name)


def _quote_string(value: str) -> str:
    from local_data_platform.engine.duckdb.row_filter import quote_string

    return quote_string(value)


def register_sources(database: str | os.PathLike, configs: Iterable[str | os.PathLike] = (),
                     catalogs: Iterable[str | os.PathLike] = (), *, mode: str = "auto",
                     sources_file: str | os.PathLike | None = None) -> SourceRegistration:
    """Make every Iceberg table LDP knows about a relation in ``database``, and declare them to dbt.

    Tables are found the way the MCP server finds them, with
    :func:`~local_data_platform.mcp_server.discovery.discover_tables`. For each one the build file
    gets a schema named after the namespace and a relation named after the table. A relation made on
    an earlier call whose table no longer exists is dropped, and a table that a config publishes from
    ``database`` itself is skipped, because it is an output of the dbt project and not an input.
    The file is opened for writing, and closed before this function returns.

    Args:
        database: The DuckDB build file. It is created when missing.
        configs: Dataset config files, or folders of ``*.json`` configs. Every Iceberg table a
            config names is a source.
        catalogs: Catalog spec files. Every table of the catalog is a source.
        mode: ``"view"``, ``"copy"`` or ``"auto"``, see the module docstring. In auto mode a table
            that DuckDB cannot scan becomes a copy.
        sources_file: Where to write the dbt sources YAML (usually ``models/_ldp_sources.yml``).
            It is rewritten only when its content changes. ``None`` writes no file.

    Returns:
        A :class:`SourceRegistration`.

    Raises:
        ConfigError: If ``mode`` is unknown, a config or catalog path is wrong, the build file is
            in use by another process, or a source name clashes with a relation dbt created.
        EngineNotFound: If ``duckdb`` is missing, or ``mode="view"`` and the iceberg extension can't be loaded.
    """
    if mode not in MODES:
        raise ConfigError(f"mode must be one of {list(MODES)}, got {mode!r}")
    duckdb = _import_duckdb()
    from local_data_platform.mcp_server.discovery import discover_tables

    database = resolve_path(database)
    discovery = discover_tables(configs, catalogs)
    result = SourceRegistration(database=database, unavailable=list(discovery.unavailable))
    try:
        tables = _without_own_outputs(discovery.tables, database, result.skipped)
        database.parent.mkdir(parents=True, exist_ok=True)
        try:
            connection = duckdb.connect(str(database))
        except duckdb.IOException as error:
            raise ConfigError(f"cannot open the dbt build file {database} for writing; is dbt running? "
                              f"{str(error).splitlines()[0]}") from error
        try:
            use_views = _use_views(connection, mode)
            _ensure_state(connection)
            previous = _read_state(connection)
            connection.begin()
            try:
                for table in tables:
                    result.sources.append(_register_one(connection, table, use_views, mode, previous))
                result.dropped = _drop_leftovers(connection, previous, result.sources)
                _write_state(connection, result.sources)
            except BaseException:
                connection.rollback()
                raise
            connection.commit()
        finally:
            connection.close()
    finally:
        discovery.close()
    if sources_file is not None:
        result.sources_file = _write_if_changed(Path(sources_file), sources_yaml(result.sources))
    logger.info("Registered %d dbt sources in %s (%s mode, %d skipped, %d dropped)", len(result.sources), database,
                result.mode, len(result.skipped), len(result.dropped))
    return result


